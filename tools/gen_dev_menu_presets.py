#!/usr/bin/env python3
"""Generate pc_port/dev_menu_presets.h from the retail debug menu's "AREA N"
presets (MAIN.CD member 11: func_800D0964 base, func_800D0BDC area 2,
func_800D1254 area 3, func_800D1B00 area 4, func_800D235C area 5,
func_800D2BC4 area 6; applied cumulatively by func_800CFCBC).

Reads the matched C of those functions and emits only their writes as data:
(op, address or index, value). No code is copied. Ops:
  W8/W16/W32  store to the live state struct at 80078E78 + offset
  FLAG        story flag n set/cleared (func_80029124: 800AE648 bit n)
  VAR         script var n = value (func_800291A0: 800BA1B8[n])
  VAR_OR80    script var n = guest byte at address | 0x80
  COPY16      guest u16 at address = guest u16 at value

  tools/gen_dev_menu_presets.py SRC_DIR > pc_port/dev_menu_presets.h
SRC_DIR is the directory holding the six matched files (800d0964.c ...).
"""
import re
import sys

PRESETS = [("800d0964", 1), ("800d0bdc", 2), ("800d1254", 3),
           ("800d1b00", 4), ("800d235c", 5), ("800d2bc4", 6)]
STRUCT = 0x80078E78
WIDTH = {"s32": 4, "u32": 4, "s16": 2, "u16": 2, "u8": 1, "s8": 1}


def num(text):
    text = text.strip()
    return int(text, 16) if text.lower().startswith("0x") else int(text)


def parse(path):
    src = open(path).read()
    widths = {m.group(2): WIDTH[m.group(1)]
              for m in re.finditer(r"\b(s32|u32|s16|u16|u8|s8)\s+(?:unk|f)([0-9A-F]{2});", src)}
    body = src[src.index("D_80078E78;"):] if "D_80078E78;" in src else src[src.index("void func_"):]
    ops = []
    for m in re.finditer(r"\b[a-z]\w*->(?:unk|f)([0-9A-F]{2})\s*=\s*([^;]+);"
                         r"|func_80029124\(([^,]+),\s*([^)]+)\);"
                         r"|func_800291A0\(([^,]+),\s*(.+?)\);"
                         r"|\n\s*(D_[0-9A-F]{8})\s*=\s*(D_[0-9A-F]{8});", body):
        if m.group(1):
            off = int(m.group(1), 16)
            ops.append(("W%d" % (8 * widths[m.group(1)]), STRUCT + off, num(m.group(2)) & 0xFFFFFFFF))
        elif m.group(3):
            ops.append(("FLAG", num(m.group(3)), 1 if num(m.group(4)) & 0xFF else 0))
        elif m.group(5):
            value = m.group(6).strip()
            # (D_x | 0x80) & 0xFF, ((D_x | 0x80) & 0xFF), (u8)(D_x | 0x80)
            ref = re.fullmatch(r"(?:\(u8\))?\(*D_([0-9A-F]{8}) \| 0x80\)(?: & 0xFF)?\)?", value)
            if ref:
                ops.append(("VAR_OR80", num(m.group(5)), int(ref.group(1), 16)))
            else:
                ops.append(("VAR", num(m.group(5)), num(value) & 0xFF))
        else:
            ops.append(("COPY16", int(m.group(7)[2:], 16), int(m.group(8)[2:], 16)))
    # Every statement of the body must have been understood.
    statements = [s for s in re.findall(r"^\s+([a-z]\w*->|func_|D_)[^\n]*;", body, re.M)]
    if len(statements) != len(ops):
        sys.exit("%s: parsed %d of %d statements" % (path, len(ops), len(statements)))
    return ops


def main():
    src_dir = sys.argv[1]
    print("/* Generated by tools/gen_dev_menu_presets.py from the retail debug")
    print(" * menu's AREA presets (MAIN.CD member 11, func_800CFCBC applies them")
    print(" * cumulatively). Data only: the writes each preset makes. */")
    print("#ifndef MUSASHI_DEV_MENU_PRESETS_H")
    print("#define MUSASHI_DEV_MENU_PRESETS_H")
    print("enum { PRESET_W8, PRESET_W16, PRESET_W32, PRESET_FLAG, PRESET_VAR, PRESET_VAR_OR80, PRESET_COPY16 };")
    print("typedef struct { unsigned char area, op; unsigned int a, b; } DevPresetOp;")
    print("static const DevPresetOp kPresetOps[] = {")
    total = 0
    for name, area in PRESETS:
        ops = parse("%s/%s.c" % (src_dir, name))
        print("    /* func_%s: area %d%s */" % (name.upper(), area, " (base)" if area == 1 else ""))
        for op, a, b in ops:
            print("    { %d, PRESET_%s, 0x%08Xu, 0x%08Xu }," % (area, op, a, b))
        total += len(ops)
    print("};")
    print("#endif")
    print("%d ops" % total, file=sys.stderr)


if __name__ == "__main__":
    main()
