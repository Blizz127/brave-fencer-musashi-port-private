#!/usr/bin/env python3
"""Generate pc_port/location_images.h: every SC location member's code image
as the formatter identifies it at 0x80128158.

For each decoded code chunk extracted/overlays/scNN/MMMM.pac0.bin (written
from the developer's own disc by tools/decode_sc_overlays.py, gitignored)
this records the FNV-1a 64 digest of its first SC_ENTRY_WORDS (178) words,
the same span_digest the formatter computes over guest RAM, and the
chunk's size. Digests and sizes only: no game bytes are written. Members
whose entry spans are identical share one row with the largest size.

  tools/gen_location_images.py > pc_port/location_images.h
"""
import glob
import os
import struct
import sys

ENTRY_BYTES = 178 * 4
MODULE_DIGEST_BYTES = 64 * 4
# Fixed-address code modules some rooms load beside their image (PAC type 1,
# stored uncompressed). The link base is where the module's own absolute
# references point: sc02_0009 (the castle-gate boss room 300E's module) runs
# at 801E4C60, confirmed from a guest RAM dump of that room (its references,
# e.g. 801E663C, land inside it and its 0x11480 bytes end at 801F60E0).
MODULE_BASES = {"sc02/0009": 0x801E4C60}
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def pac_chunks(data):
    """(type, payload) for each PAC chunk of a raw SC member."""
    offset = 0
    while offset + 32 <= len(data) and data[offset:offset + 4] == b"PAC\0":
        header = struct.unpack_from("<8I", data, offset)
        yield header[1], data[offset + 0x800:offset + header[3]]
        step = (header[3] + 0x7FF) & ~0x7FF
        if not step:
            break
        offset += step


def fnv1a64(data):
    h = 0xCBF29CE484222325
    for b in data:
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    rows = {}
    for path in sorted(glob.glob(os.path.join(root, "extracted/overlays/sc0*/*.pac0.bin"))):
        data = open(path, "rb").read()
        if len(data) < ENTRY_BYTES:
            continue
        member = os.path.relpath(path, os.path.join(root, "extracted/overlays"))[:-len(".pac0.bin")]
        digest = fnv1a64(data[:ENTRY_BYTES])
        size = len(data) & ~3
        names, best = rows.get(digest, ([], 0))
        rows[digest] = (names + [member.replace("/", "_")], max(best, size))
    # Whole room images stored uncompressed (PAC type 1) that load at
    # 0x80128158 like the decoded ones: their first word is the entry's
    # stack-frame prologue (addiu sp, sp, -n).
    modules = []
    for path in sorted(glob.glob(os.path.join(root, "extracted/overlays/sc0*/[0-9][0-9][0-9][0-9].bin"))):
        member = os.path.relpath(path, os.path.join(root, "extracted/overlays"))[:-len(".bin")]
        for kind, payload in pac_chunks(open(path, "rb").read()):
            if kind != 1 or len(payload) < ENTRY_BYTES:
                continue
            if member in MODULE_BASES:
                modules.append((member, MODULE_BASES[member], len(payload) & ~3,
                                fnv1a64(payload[:MODULE_DIGEST_BYTES])))
            elif (struct.unpack_from("<I", payload, 0)[0] & 0xFFFF8000) == 0x27BD8000:
                digest = fnv1a64(payload[:ENTRY_BYTES])
                names, best = rows.get(digest, ([], 0))
                rows[digest] = (names + [member.replace("/", "_") + "(raw)"], max(best, len(payload) & ~3))
    if not rows:
        sys.exit("gen_location_images: no decoded SC members under extracted/overlays")
    print("/* Generated by tools/gen_location_images.py: the SC location member code")
    print(" * images, identified by the FNV-1a 64 digest of their 178-word entry span")
    print(" * at 0x80128158, and each image's code size in bytes. Digests and sizes")
    print(" * only (no game bytes). */")
    print("#ifndef MUSASHI_LOCATION_IMAGES_H")
    print("#define MUSASHI_LOCATION_IMAGES_H")
    print("#include <stdint.h>")
    print("static const struct { uint64_t entry_digest; uint32_t code_bytes; } kLocationImages[] = {")
    largest = 0
    for digest, (names, size) in sorted(rows.items(), key=lambda kv: kv[1][0]):
        print("    { 0x%016xull, %7du }, /* %s */" % (digest, size, " ".join(names)))
        largest = max(largest, size)
    print("};")
    print("enum { LOCATION_IMAGE_MAX_BYTES = %d };" % largest)
    print("/* Fixed-address code modules: link base, size, FNV-1a 64 of the first")
    print(" * 64 words, checked against guest RAM before any of it is admitted. */")
    print("static const struct { uint32_t base, bytes; uint64_t digest; } kCodeModules[] = {")
    for member, base, size, digest in modules:
        print("    { 0x%08xu, %6du, 0x%016xull }, /* %s */" % (base, size, digest, member.replace("/", "_")))
    print("};")
    print("#endif")
    print("%d images, %d members" % (len(rows), sum(len(n) for n, _ in rows.values())), file=sys.stderr)


if __name__ == "__main__":
    main()
